const int file_count = 7;

// Função para buscar arquivo por nome
const struct file_entry* find_file(const char* name) {
  for (int i = 0; i < file_count; i++) {
    if (name_eq(files[i].name, name)) {
      return &files[i];
    }
  }
  return 0;
}
